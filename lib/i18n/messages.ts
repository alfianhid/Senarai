export function t(locale: Locale, key: MessageKey, vars?: Record<string, string>): string {
  let value = messages[locale][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) value = value.replace(`{${k}}`, v);
  }
  return value;
}
