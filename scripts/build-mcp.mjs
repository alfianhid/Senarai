// Bundles mcp/server.ts into one file the MCP client can launch with plain node.
//
// The client config must not depend on this project's tsconfig, path aliases or
// TypeScript loader, so the bundle is self-contained for our own code and leaves
// the MCP SDK and zod to be resolved from node_modules at runtime.
//
// Usage: node scripts/build-mcp.mjs
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

const result = await build({
  entryPoints: ['mcp/server.ts'],
  outfile: 'mcp/dist/server.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  absWorkingDir: root,
  // Resolved from node_modules next to the bundle at runtime.
  external: ['@modelcontextprotocol/sdk', '@modelcontextprotocol/sdk/*', 'zod'],
  alias: { '@': root },
  banner: {
    js: '// Generated by scripts/build-mcp.mjs — do not edit. Run `npm run mcp:build`.',
  },
  logLevel: 'info',
});

if (result.errors.length > 0) process.exit(1);
console.log('mcp/dist/server.mjs built');
